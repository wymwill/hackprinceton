/** Pool: add a favor (up to favors_per_player). Pledge: replace your one pledge. */
create or replace function public.propose_series_favor(p_series_id uuid, p_description text) returns public.series_favors
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; p public.bet_series_participants; f public.series_favors; v_text text; v_count int;
begin
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  select * into p from public.bet_series_participants where series_id = s.id and user_id = auth.uid();
  if not found then perform public._bs_fail('not_member', 'You''re not in this series.'); end if;
  if s.status <> 'LOBBY' then perform public._bs_fail('favor_proposals_closed', 'Favors are locked once betting starts.'); end if;
  if not p.plays then perform public._bs_fail('not_player', 'You''re hosting without playing, so you don''t add favors.'); end if;
  if s.stake_mode = 'MONEY' then perform public._bs_fail('wrong_mode', 'This series uses real money, not favors.'); end if;
  v_text := regexp_replace(trim(coalesce(p_description, '')), '\s+', ' ', 'g');
  if char_length(v_text) not between 3 and 120 then perform public._bs_fail('invalid_favor', 'Describe the favor in a few words (3 to 120 characters).'); end if;
  if s.stake_mode = 'PLEDGE' then
    update public.series_favors set withdrawn = true where series_id = s.id and submitted_by = auth.uid() and not withdrawn;
    update public.bet_series_participants set ready = false where series_id = s.id and user_id = auth.uid();
  else
    select count(*) into v_count from public.series_favors where series_id = s.id and submitted_by = auth.uid() and not withdrawn;
    if v_count >= s.favors_per_player then
      perform public._bs_fail('favor_limit', format('You can add up to %s favor%s.', s.favors_per_player, case when s.favors_per_player = 1 then '' else 's' end));
    end if;
    -- The pool changed, so everyone's agreement to it has to be given again.
    update public.bet_series_participants set ready = false where series_id = s.id;
  end if;
  insert into public.series_favors(series_id, submitted_by, description) values (s.id, auth.uid(), v_text) returning * into f;
  perform public._bs_log(s.id, p.display_name || case when s.stake_mode = 'PLEDGE' then ' pledged a favor.' else ' added a favor to the pool.' end);
  return f;
end $$;

create or replace function public.withdraw_series_favor(p_favor_id uuid) returns boolean
language plpgsql security definer set search_path=public as $$
declare f public.series_favors; s public.bet_series;
begin
  select * into f from public.series_favors where id = p_favor_id and not withdrawn;
  if not found or not public.is_bet_series_member(f.series_id, auth.uid()) then perform public._bs_fail('favor_not_found', 'That favor doesn''t exist.'); end if;
  select * into s from public.bet_series where id = f.series_id for update;
  if s.status <> 'LOBBY' then perform public._bs_fail('favor_proposals_closed', 'Favors are locked once betting starts.'); end if;
  if f.submitted_by <> auth.uid() then perform public._bs_fail('not_author', 'You can only remove your own favors.'); end if;
  update public.series_favors set withdrawn = true where id = f.id;
  if s.stake_mode = 'SHARED_FAVOR_POOL' then
    update public.bet_series_participants set ready = false where series_id = s.id;
  else
    update public.bet_series_participants set ready = false where series_id = s.id and user_id = auth.uid();
  end if;
  return true;
end $$;

/** Shared pool: agree (or stop agreeing) to someone else's favor. Taking agreement back un-readies you. */
create or replace function public.consent_series_favor(p_favor_id uuid, p_consent boolean) returns public.series_favors
language plpgsql security definer set search_path=public as $$
declare f public.series_favors; s public.bet_series; p public.bet_series_participants;
begin
  select * into f from public.series_favors where id = p_favor_id and not withdrawn;
  if not found or not public.is_bet_series_member(f.series_id, auth.uid()) then perform public._bs_fail('favor_not_found', 'That favor doesn''t exist.'); end if;
  select * into s from public.bet_series where id = f.series_id for update;
  if s.status <> 'LOBBY' then perform public._bs_fail('favor_proposals_closed', 'Favors are locked once betting starts.'); end if;
  if s.stake_mode <> 'SHARED_FAVOR_POOL' then perform public._bs_fail('wrong_mode', 'Only a shared pool needs everyone to agree.'); end if;
  select * into p from public.bet_series_participants where series_id = s.id and user_id = auth.uid();
  if not p.plays then perform public._bs_fail('not_player', 'Only players agree to favors.'); end if;
  if f.submitted_by = auth.uid() then perform public._bs_fail('cannot_consent_own_favor', 'You wrote this one, so you already agree to it.'); end if;
  if p_consent then
    update public.series_favors set consented_by = array(select distinct unnest(consented_by || auth.uid())) where id = f.id returning * into f;
  else
    update public.series_favors set consented_by = array_remove(consented_by, auth.uid()) where id = f.id returning * into f;
    update public.bet_series_participants set ready = false where series_id = s.id and user_id = auth.uid();
  end if;
  return f;
end $$;

/** "I'm ready": I've read the rules. In a shared pool it also agrees to every favor in it right now. */
create or replace function public.set_series_ready(p_series_id uuid, p_ready boolean) returns boolean
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; p public.bet_series_participants;
begin
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  select * into p from public.bet_series_participants where series_id = s.id and user_id = auth.uid();
  if not found then perform public._bs_fail('not_member', 'You''re not in this series.'); end if;
  if s.status <> 'LOBBY' then perform public._bs_fail('series_not_lobby', 'Betting has already started.'); end if;
  if not p.plays then perform public._bs_fail('not_player', 'You''re hosting without playing.'); end if;
  if p_ready and s.stake_mode <> 'MONEY' and not exists (
    select 1 from public.series_favors where series_id = s.id and submitted_by = auth.uid() and not withdrawn
  ) then
    perform public._bs_fail('favors_missing', case when s.stake_mode = 'PLEDGE' then 'Pledge your favor first.' else 'Add at least one favor to the pool first.' end);
  end if;
  if p_ready and s.stake_mode = 'SHARED_FAVOR_POOL' then
    update public.series_favors set consented_by = array_append(consented_by, auth.uid())
    where series_id = s.id and not withdrawn and submitted_by <> auth.uid() and not (auth.uid() = any(consented_by));
  end if;
  update public.bet_series_participants set ready = coalesce(p_ready, false) where series_id = s.id and user_id = auth.uid();
  return coalesce(p_ready, false);
end $$;

/** Host writes a bet: in the lobby, or while running when the series allows it (it opens right away). */
create or replace function public.create_series_bet(p_series_id uuid, p_question text) returns public.series_bets
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; b public.series_bets; v_q text; v_n int; v_pos int;
begin
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  if s.host_user_id <> auth.uid() then perform public._bs_fail('not_host', 'Only the host can do that.'); end if;
  v_q := regexp_replace(trim(coalesce(p_question, '')), '\s+', ' ', 'g');
  if char_length(v_q) not between 3 and 300 then perform public._bs_fail('invalid_question', 'Write the YES/NO question (3 to 300 characters).'); end if;
  if s.status = 'ACTIVE' and s.bet_creation <> 'DURING' then perform public._bs_fail('questions_locked', 'This series locked its bets before it started.'); end if;
  if s.status not in ('LOBBY','ACTIVE') then perform public._bs_fail('series_over', 'This series is over.'); end if;
  select count(*), coalesce(max(position), 0) + 1 into v_n, v_pos from public.series_bets where series_id = s.id;
  if v_n >= s.planned_bet_count then
    perform public._bs_fail('planned_questions_full', format('This series has %s bet%s, and they''re all written.', s.planned_bet_count, case when s.planned_bet_count = 1 then '' else 's' end));
  end if;
  if s.status = 'LOBBY' then
    insert into public.series_bets(series_id, question, created_by, status, position) values (s.id, v_q, auth.uid(), 'PLANNED', v_pos) returning * into b;
  else
    insert into public.series_bets(series_id, question, created_by, status, position, opened_at)
    values (s.id, v_q, auth.uid(), 'OPEN', v_pos, now()) returning * into b;
    perform public._bs_log(s.id, 'New bet: ' || v_q);
  end if;
  return b;
end $$;

create or replace function public.remove_series_bet(p_series_id uuid, p_bet_id uuid) returns boolean
language plpgsql security definer set search_path=public as $$
declare s public.bet_series;
begin
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  if s.host_user_id <> auth.uid() then perform public._bs_fail('not_host', 'Only the host can do that.'); end if;
