-- Bet Series: the full rule set on top of migrations 0001–0006.
--
-- Adds what the Bet Series spec asks for that the first Supabase version left out:
--   * three modes: SHARED_FAVOR_POOL (C), PLEDGE (B, each player pledges their own favor), MONEY (A, recorded only)
--   * a withdrawal window, tiebreaks (first to reach / random), adding bets during the series,
--     favors per player, exclusive or reusable pools, and a host who can sit out
--   * invite codes, display names, a ready check, leaving, removing favors and lobby bets
--   * stored per-player results for every settled bet, an activity feed, and one state read for the app
-- and fixes the leaderboard's loser flag (it marked everyone outside the top X).
--
-- Every write is still a security-definer RPC that locks the series row, so balance
-- checks and settlement can't race. Errors carry a readable message and a stable
-- code in the `hint` field; the API maps the code to an HTTP status.

