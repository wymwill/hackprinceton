// Builds the SQL that brings the live Supabase project up to date, from the files
// in supabase/migrations (so it can't drift from them).
//
// The live project ran 0001–0008, then 0012 (friends and clans) before 0009–0011
// were merged. This applies what's missing, in order: 0009, 0010, 0011, 0013.
// Everything runs in one transaction: if any statement fails, nothing changes.
// A preflight check refuses to run unless the database is in exactly that state.
//
//   node scripts/catchup-sql.mjs > catchup.sql     # then paste into the SQL editor
//
// supabase/tests/upgrade.test.mjs runs this same SQL on a copy of that state.
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "supabase", "migrations");
export const CATCHUP = [
  "202611140009_multi_outcome_bets.sql",
  "202611140010_range_bets.sql",
  "202611140011_pledge_changes_reset_ready.sql",
  "202611140013_clan_chat.sql",
];

const PREFLIGHT = `
-- Preflight: only run on a database that has 0001–0008 and 0012 but not 0009 or 0013.
do $preflight$
begin
  if to_regprocedure('public.my_series_state()') is null or to_regclass('public.series_activity') is null then
    raise exception 'Stopped: the Bet Series rules (0007) are missing. Apply 0001–0008 first.';
  end if;
  if to_regclass('public.clans') is null or to_regclass('public.clan_members') is null then
    raise exception 'Stopped: friends and clans (0012) are missing. Apply 202611140012_friends_and_clans.sql first.';
  end if;
  if to_regclass('public.series_bet_outcomes') is not null then
    raise exception 'Stopped: 0009 (multiple-choice bets) is already applied. Apply only the migrations still missing.';
  end if;
  if to_regclass('public.clan_messages') is not null then
    raise exception 'Stopped: 0013 (clan chat) is already applied.';
  end if;
  -- 0009 turns every existing bet into a YES/NO bet; that needs every wager, result and winner to be YES or NO.
  if exists (select 1 from public.series_wagers where outcome is null or outcome not in ('YES','NO'))
     or exists (select 1 from public.series_bet_results where side not in ('YES','NO'))
     or exists (select 1 from public.series_bets where winning_outcome is not null and winning_outcome not in ('YES','NO')) then
    raise exception 'Stopped: some existing wagers, results or bets have a side other than YES/NO, which 0009 can''t convert. Nothing was changed.';
  end if;
end
$preflight$;
`;

export async function catchupSql() {
  const parts = [
    "-- Alea: catch-up migration for the live project (generated by scripts/catchup-sql.mjs).",
    `-- Applies, in order: ${CATCHUP.join(", ")}.`,
    "-- One transaction: if anything fails, nothing is changed.",
    "begin;",
    PREFLIGHT,
  ];
  for (const f of CATCHUP) {
    parts.push(`\n-- ======================================================================\n-- ${f}\n-- ======================================================================\n`);
    parts.push(await readFile(path.join(DIR, f), "utf8"));
  }
  parts.push("\n-- Have the API see the new functions and tables right away.\nnotify pgrst, 'reload schema';\n\ncommit;\n");
  return parts.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.stdout.write(await catchupSql());
