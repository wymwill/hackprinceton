/** Start: checks the blockers, hands out coins once, opens every written bet, draws the random order. Repeating it is harmless. */
create or replace function public.start_bet_series(p_series_id uuid) returns public.bet_series
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; v_code text; v_message text;
begin
  if auth.uid() is null then perform public._bs_fail('unauthorized', 'Sign in first.'); end if;
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  if s.host_user_id <> auth.uid() then perform public._bs_fail('not_host', 'Only the host can do that.'); end if;
  if s.status = 'ACTIVE' then return s; end if;
  if s.status <> 'LOBBY' then perform public._bs_fail('series_not_lobby', 'This series has already started.'); end if;
  select bl.code, bl.message into v_code, v_message from public._bs_blockers(s.id) bl limit 1;
  if v_code is not null then perform public._bs_fail(v_code, v_message); end if;
  update public.bet_series_participants set balance = case when plays then s.initial_bankroll else 0 end where series_id = s.id;
  update public.series_bets set status = 'OPEN', opened_at = now() where series_id = s.id and status = 'PLANNED';
  update public.bet_series set status = 'ACTIVE', started_at = now(),
    random_order = case when s.tiebreak = 'RANDOM'
      then (select array_agg(user_id order by random()) from public.bet_series_participants where series_id = s.id and plays) end
  where id = s.id returning * into s;
  perform public._bs_log(s.id, 'Betting started. Everyone got ' || public._bs_coins(s.initial_bankroll) || ' coins.');
  return s;
end $$;

-- ---------- betting ----------

create or replace function public.place_series_wager(p_series_id uuid, p_bet_id uuid, p_outcome text, p_amount bigint) returns public.series_wagers
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; b public.series_bets; p public.bet_series_participants; w public.series_wagers;
  v_side text := upper(coalesce(p_outcome, '')); v_prior text; v_window boolean;
begin
  if auth.uid() is null then perform public._bs_fail('unauthorized', 'Sign in first.'); end if;
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  select * into p from public.bet_series_participants where series_id = s.id and user_id = auth.uid() for update;
  if not found then perform public._bs_fail('not_member', 'You''re not in this series.'); end if;
  if not p.plays then perform public._bs_fail('not_player', 'You''re hosting without playing, so you can''t bet.'); end if;
  if s.status <> 'ACTIVE' then
    perform public._bs_fail('series_not_active', case when s.status = 'LOBBY' then 'Betting hasn''t started yet.' else 'This series is over.' end);
  end if;
  select * into b from public.series_bets where id = p_bet_id and series_id = s.id for update;
  if not found then perform public._bs_fail('bet_not_found', 'That bet doesn''t exist.'); end if;
  if b.status <> 'OPEN' then
    perform public._bs_fail('bet_not_open', case when b.status = 'LOCKED' then 'Betting is closed on this one.' else 'This bet is finished.' end);
  end if;
  if v_side not in ('YES','NO') then perform public._bs_fail('invalid_wager', 'Pick YES or NO.'); end if;
  if p_amount is null or p_amount < 1 then perform public._bs_fail('invalid_wager', 'Wager at least 1 coin.'); end if;
  select outcome into v_prior from public.series_wagers where bet_id = b.id and user_id = auth.uid() limit 1;
  if v_prior is not null and v_prior <> v_side then
    v_window := s.withdraw_minutes > 0 and now() < b.opened_at + make_interval(mins => s.withdraw_minutes);
    perform public._bs_fail('cannot_switch_sides', format('You''re on %s. You can add to it%s.', v_prior, case when v_window then ', or withdraw and pick again' else '' end));
  end if;
  if p.balance < p_amount then perform public._bs_fail('insufficient_balance', 'You only have ' || public._bs_coins(p.balance) || ' coins free.'); end if;
  update public.bet_series_participants set balance = balance - p_amount where series_id = s.id and user_id = auth.uid();
  insert into public.series_wagers(bet_id, user_id, outcome, amount) values (b.id, auth.uid(), v_side, p_amount) returning * into w;
  perform public._bs_log(s.id, p.display_name || case when v_prior is null then ' put ' else ' added ' end
    || public._bs_coins(p_amount) || ' on ' || v_side || ': ' || b.question);
  return w;
end $$;

/** Take your whole wager back, inside the window after the bet opened. Returns the coins refunded. */
create or replace function public.withdraw_series_wager(p_series_id uuid, p_bet_id uuid) returns bigint
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; b public.series_bets; v_total bigint;
begin
  select * into s from public.bet_series where id = p_series_id for update;
  if not found then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  if not public.is_bet_series_member(s.id, auth.uid()) then perform public._bs_fail('not_member', 'You''re not in this series.'); end if;
  if s.status <> 'ACTIVE' then
    perform public._bs_fail('series_not_active', case when s.status = 'LOBBY' then 'Betting hasn''t started yet.' else 'This series is over.' end);
  end if;
  select * into b from public.series_bets where id = p_bet_id and series_id = s.id for update;
  if not found then perform public._bs_fail('bet_not_found', 'That bet doesn''t exist.'); end if;
  if b.status <> 'OPEN' then
    perform public._bs_fail('bet_not_open', case when b.status = 'LOCKED' then 'Betting is closed on this one.' else 'This bet is finished.' end);
  end if;
  select sum(amount) into v_total from public.series_wagers where bet_id = b.id and user_id = auth.uid();
  if v_total is null then perform public._bs_fail('no_wager', 'You don''t have a wager on this bet.'); end if;
  if s.withdraw_minutes <= 0 then perform public._bs_fail('withdraw_closed', 'This series doesn''t allow withdrawals.'); end if;
  if now() >= b.opened_at + make_interval(mins => s.withdraw_minutes) then perform public._bs_fail('withdraw_closed', 'The withdrawal window has passed.'); end if;
  delete from public.series_wagers where bet_id = b.id and user_id = auth.uid();
  update public.bet_series_participants set balance = balance + v_total where series_id = s.id and user_id = auth.uid();
  perform public._bs_log(s.id, public._bs_name(s.id, auth.uid()) || ' withdrew from: ' || b.question);
  return v_total;
end $$;

