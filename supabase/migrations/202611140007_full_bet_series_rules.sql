/**
 * Shared pool: winner rank i picks a favor for loser rank n-i+1. Any favor in the pool,
 * as long as that loser wrote it or agreed to it. Exclusive pools go in rank order and a
 * favor can only be held once. After a decline, the winner picks again.
 */
create or replace function public.assign_series_favor(p_series_id uuid, p_loser_id uuid, p_favor_id uuid) returns public.series_favor_assignments
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; a public.series_favor_assignments; f public.series_favors; v_waiting uuid;
begin
  select * into s from public.bet_series where id = p_series_id for update;
  if not found or not public.is_bet_series_member(p_series_id, auth.uid()) then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  if s.stake_mode <> 'SHARED_FAVOR_POOL' then perform public._bs_fail('wrong_mode', 'Favors aren''t picked in this mode.'); end if;
  if s.status <> 'COMPLETED' then perform public._bs_fail('series_not_complete', 'Favors are picked once the series ends.'); end if;
  select * into a from public.series_favor_assignments where series_id = s.id and loser_id = p_loser_id for update;
  if not found then perform public._bs_fail('not_loser', 'That player doesn''t owe a favor.'); end if;
  if a.winner_id is distinct from auth.uid() then perform public._bs_fail('not_winner', public._bs_name(s.id, a.winner_id) || ' picks this favor.'); end if;
  if a.status in ('PENDING_CONSENT','CONSENTED') then perform public._bs_fail('already_picked', 'You already picked.'); end if;
  select * into f from public.series_favors where id = p_favor_id and series_id = s.id and not withdrawn;
  if not found then perform public._bs_fail('favor_not_found', 'That favor isn''t in the pool.'); end if;
  if f.submitted_by <> p_loser_id and not (p_loser_id = any(f.consented_by)) then
    perform public._bs_fail('favor_lacks_consent', public._bs_name(s.id, p_loser_id) || ' hasn''t agreed to that favor.');
  end if;
  if s.exclusive_pool then
    select winner_id into v_waiting from public.series_favor_assignments
    where series_id = s.id and position < a.position and status = 'PICKING' order by position limit 1;
    if v_waiting is not null then perform public._bs_fail('picks_in_order', public._bs_name(s.id, v_waiting) || ' picks first.'); end if;
    if exists (select 1 from public.series_favor_assignments where series_id = s.id and favor_id = f.id and id <> a.id and status in ('PENDING_CONSENT','CONSENTED')) then
      perform public._bs_fail('favor_taken', 'Someone already picked that favor.');
    end if;
  end if;
  update public.series_favor_assignments set favor_id = f.id, text = f.description, status = 'PENDING_CONSENT', responded_at = null
  where id = a.id returning * into a;
  perform public._bs_log(s.id, public._bs_name(s.id, auth.uid()) || ' picked a favor for ' || public._bs_name(s.id, p_loser_id) || '.');
  return a;
end $$;

/** The loser accepts or declines the favor picked for them. Nothing is binding until they accept. */
create or replace function public.respond_series_favor_assignment(p_assignment_id uuid, p_accept boolean) returns public.series_favor_assignments
language plpgsql security definer set search_path=public as $$
declare a public.series_favor_assignments;
begin
  update public.series_favor_assignments
  set status = case when p_accept then 'CONSENTED' else 'DECLINED' end, responded_at = now()
  where id = p_assignment_id and loser_id = auth.uid() and status = 'PENDING_CONSENT'
  returning * into a;
  if a.id is null then perform public._bs_fail('assignment_not_pending', 'There''s no favor waiting for your answer.'); end if;
  perform public._bs_log(a.series_id, public._bs_name(a.series_id, auth.uid()) || case when p_accept then ' accepted their favor.' else ' declined their favor.' end);
  return a;
end $$;

create or replace function public.mark_series_favor_done(p_series_id uuid) returns public.series_favor_assignments
language plpgsql security definer set search_path=public as $$
declare s public.bet_series; a public.series_favor_assignments;
begin
  select * into s from public.bet_series where id = p_series_id;
  if not found or not public.is_bet_series_member(p_series_id, auth.uid()) then perform public._bs_fail('series_not_found', 'That series doesn''t exist.'); end if;
  select * into a from public.series_favor_assignments where series_id = s.id and loser_id = auth.uid() for update;
  if not found then perform public._bs_fail('not_loser', 'You don''t owe a favor.'); end if;
  if s.stake_mode = 'MONEY' then perform public._bs_fail('wrong_mode', 'There''s no favor to complete in this mode.'); end if;
  if a.favor_id is null then perform public._bs_fail('not_picked', 'Your favor hasn''t been picked yet.'); end if;
  if a.status <> 'CONSENTED' then perform public._bs_fail('not_accepted', 'Accept the favor first.'); end if;
  update public.series_favor_assignments set done = true where id = a.id returning * into a;
  perform public._bs_log(s.id, public._bs_name(s.id, auth.uid()) || ' did their favor.');
  return a;
end $$;

