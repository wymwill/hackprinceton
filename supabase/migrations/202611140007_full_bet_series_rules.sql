/** A whole number from a JSON setting, the default when it's missing, or null when it's there but not a whole number. */
create or replace function public._bs_int(p jsonb, k text, d int) returns int language sql immutable as $$
  select case
    when p is null or not (p ? k) or jsonb_typeof(p->k) = 'null' then d
    when jsonb_typeof(p->k) = 'number' and (p->>k) ~ '^-?[0-9]{1,9}$' then (p->>k)::int
  end
$$;

create or replace function public._bs_bool(p jsonb, k text, d boolean) returns boolean language sql immutable as $$
  select case when p is not null and jsonb_typeof(p->k) = 'boolean' then (p->>k)::boolean else d end
$$;

/** Clean up after someone leaves or is removed in the lobby. */
create or replace function public._bs_drop_member(p_series_id uuid, p_user_id uuid, p_mode text) returns void language plpgsql set search_path=public as $$
declare v_had boolean;
begin
  select exists (select 1 from public.series_favors where series_id = p_series_id and submitted_by = p_user_id and not withdrawn) into v_had;
  update public.series_favors set withdrawn = true where series_id = p_series_id and submitted_by = p_user_id;
  update public.series_favors set consented_by = array_remove(consented_by, p_user_id) where series_id = p_series_id;
  delete from public.bet_series_participants where series_id = p_series_id and user_id = p_user_id;
  -- The shared pool changed, so everyone's agreement to it has to be given again.
  if v_had and p_mode = 'SHARED_FAVOR_POOL' then
    update public.bet_series_participants set ready = false where series_id = p_series_id;
  end if;
end $$;

/** Everything still stopping the host from starting, in order. Empty = ready to go. */
create or replace function public._bs_blockers(p_series_id uuid) returns table(code text, message text)
language plpgsql stable set search_path=public as $$
declare s public.bet_series; v_n int; v_x int; v_missing text; v_waiting text; v_bets int;
begin
  select * into s from public.bet_series where id = p_series_id;
  select count(*) into v_n from public.bet_series_participants where series_id = s.id and plays;
  v_x := s.loser_count;
  if v_n < 2 then
    code := 'one_person'; message := 'At least 2 players need to join.'; return next;
  elsif s.stake_mode = 'SHARED_FAVOR_POOL' and 2 * v_x > v_n then
    code := 'too_few_participants';
    message := format('A shared pool needs at least %s players so the top %s can pick for the bottom %s.', 2 * v_x, v_x, v_x);
    return next;
  elsif v_x >= v_n then
    code := 'too_few_participants';
    message := format('Need more than %s player%s for %s to lose.', v_x, case when v_x = 1 then '' else 's' end, v_x);
    return next;
  end if;
  if s.stake_mode <> 'MONEY' then
    select string_agg(p.display_name, ', ' order by p.join_seq) into v_missing
    from public.bet_series_participants p
    where p.series_id = s.id and p.plays
      and not exists (select 1 from public.series_favors f where f.series_id = s.id and f.submitted_by = p.user_id and not f.withdrawn);
    if v_missing is not null then code := 'favors_missing'; message := 'Waiting on favors from ' || v_missing || '.'; return next; end if;
  end if;
  select string_agg(p.display_name, ', ' order by p.join_seq) into v_waiting
  from public.bet_series_participants p where p.series_id = s.id and p.plays and not p.ready;
  if v_waiting is not null then code := 'not_ready'; message := 'Not ready yet: ' || v_waiting || '.'; return next; end if;
  select count(*) into v_bets from public.series_bets where series_id = s.id;
  if s.bet_creation = 'UPFRONT' and v_bets < s.planned_bet_count then
    code := 'planned_questions_required';
    message := format('Write all %s bets before starting (%s so far).', s.planned_bet_count, v_bets);
    return next;
  end if;
end $$;

/**
 * The board. Ranked by settled coins (open wagers don't move it until they settle).
 * Ties: FIRST puts whoever reached that score first ahead (the bet that last changed
 * their coins resolved earlier), then the earlier wager on that bet, then join order.
 * RANDOM uses the order drawn at start. Once the series ends, the frozen order wins.
 */
create or replace function public._bs_standings(p_series_id uuid)
returns table(rank int, user_id uuid, coins bigint, at_stake bigint, available bigint, reached_seq int, losing boolean)
language sql stable set search_path=public as $$
  with s as (select * from public.bet_series where id = p_series_id),
  pl as (
    select p.user_id, p.balance, row_number() over (order by p.join_seq) as join_ord
    from public.bet_series_participants p where p.series_id = p_series_id and p.plays
  ),
  st as (
    select w.user_id, sum(w.amount)::bigint as amt
    from public.series_wagers w join public.series_bets b on b.id = w.bet_id
    where b.series_id = p_series_id and b.status in ('OPEN','LOCKED') group by w.user_id
  ),
  re as (
    select distinct on (r.user_id) r.user_id, b.seq, r.first_seq
    from public.series_bet_results r join public.series_bets b on b.id = r.bet_id
    where b.series_id = p_series_id and b.status = 'RESOLVED' and r.net <> 0
    order by r.user_id, b.seq desc
  ),
  base as (
    select pl.user_id,
      case when s.status = 'LOBBY' then s.initial_bankroll else pl.balance + coalesce(st.amt, 0) end as coins,
      coalesce(st.amt, 0)::bigint as at_stake,
      case when s.status = 'LOBBY' then s.initial_bankroll else pl.balance end as available,
      coalesce(re.seq, 0) as seq, re.first_seq, pl.join_ord,
      coalesce(array_position(s.random_order, pl.user_id), pl.join_ord::int) as rnd,
      array_position(s.final_order, pl.user_id) as fin,
      s.tiebreak, s.status, s.loser_count
    from pl cross join s left join st on st.user_id = pl.user_id left join re on re.user_id = pl.user_id
  ),
  ranked as (
    select b.*,
      row_number() over (order by
        b.fin nulls last,
        b.coins desc,
        case when b.tiebreak = 'RANDOM' then b.rnd else 0 end,
        case when b.tiebreak = 'RANDOM' then 0 else b.seq end,
        case when b.tiebreak = 'RANDOM' then null else b.first_seq end asc nulls first,
        b.join_ord) as rk,
      count(*) over () as n
    from base b
  )
  select rk::int, user_id, coins::bigint, at_stake, available::bigint, seq::int, (status <> 'LOBBY' and rk > n - loser_count)
  from ranked order by rk
$$;

/** Freeze the final order and write down what the losers owe, by mode. */
create or replace function public._bs_finish(p_series_id uuid) returns void language plpgsql set search_path=public as $$
declare s public.bet_series; v_order uuid[]; v_n int; v_x int; i int; v_loser uuid; f public.series_favors;
begin
  select * into s from public.bet_series where id = p_series_id;
  select array_agg(st.user_id order by st.rank) into v_order from public._bs_standings(p_series_id) st;
  v_n := coalesce(array_length(v_order, 1), 0);
  v_x := least(s.loser_count, v_n);
  update public.bet_series set status = 'COMPLETED', final_order = v_order, completed_at = now() where id = s.id;
  for i in 1..v_x loop
    if s.stake_mode = 'SHARED_FAVOR_POOL' then
      -- Rank 1 picks for last place, rank 2 for second-to-last, and so on.
      insert into public.series_favor_assignments(series_id, winner_id, loser_id, position, status)
      values (s.id, v_order[i], v_order[v_n - i + 1], i, 'PICKING');
    else
      v_loser := v_order[v_n - v_x + i];
      f := null;
      if s.stake_mode = 'PLEDGE' then
        select * into f from public.series_favors
        where series_id = s.id and submitted_by = v_loser and not withdrawn order by created_at desc limit 1;
      end if;
      -- A pledge is the loser's own favor, so it's already agreed. Money is recorded only.
      insert into public.series_favor_assignments(series_id, loser_id, favor_id, text, position, status)
      values (s.id, v_loser, f.id, f.description, i, 'CONSENTED');
    end if;
  end loop;
  if v_n > 0 then perform public._bs_log(s.id, 'Series over. ' || public._bs_name(s.id, v_order[1]) || ' finished first.'); end if;
end $$;

create or replace function public._bs_maybe_finish(p_series_id uuid) returns void language plpgsql set search_path=public as $$
declare s public.bet_series; v_total int; v_final int;
begin
  select * into s from public.bet_series where id = p_series_id;
  if s.status <> 'ACTIVE' then return; end if;
  select count(*), count(*) filter (where status in ('RESOLVED','CANCELLED')) into v_total, v_final
  from public.series_bets where series_id = p_series_id;
  if v_total = s.planned_bet_count and v_final = v_total then perform public._bs_finish(p_series_id); end if;
end $$;

/**
 * Settle a bet. Winners split the whole pool by stake; rounding leftovers go one coin
 * each to the biggest winning stakes (earlier wager first), so payouts add up to the
 * pool exactly. Canceled, one-sided, or nobody on the winning side: everyone is refunded.
 * A null outcome means "refund" (used when locking a one-sided pool).
 */
create or replace function public._bs_settle(p_series_id uuid, p_bet_id uuid, p_outcome text, p_cancel boolean) returns jsonb
language plpgsql set search_path=public as $$
declare b public.series_bets; v_total bigint; v_win bigint; v_refund boolean; v_left bigint; v_seq int; v_payouts jsonb;
begin
  select * into b from public.series_bets where id = p_bet_id;
  select coalesce(sum(amount), 0) into v_total from public.series_wagers where bet_id = p_bet_id;
  select coalesce(sum(amount), 0) into v_win from public.series_wagers where bet_id = p_bet_id and outcome = p_outcome;
  v_refund := p_cancel or v_win = 0 or v_win = v_total;

  insert into public.series_bet_results(bet_id, user_id, side, stake, payout, net, first_at, first_seq)
  select p_bet_id, w.user_id, min(w.outcome), sum(w.amount), 0, 0, min(w.created_at), min(w.placed_seq)
  from public.series_wagers w where w.bet_id = p_bet_id group by w.user_id;

  if v_refund then
    update public.series_bet_results set payout = stake where bet_id = p_bet_id;
  else
    update public.series_bet_results set payout = (stake * v_total) / v_win where bet_id = p_bet_id and side = p_outcome;
    select v_total - coalesce(sum(payout), 0) into v_left from public.series_bet_results where bet_id = p_bet_id;
    -- Flooring loses less than one coin per winner, so one pass hands out the rest.
    update public.series_bet_results r set payout = r.payout + 1
    from (
      select x.user_id from public.series_bet_results x
      where x.bet_id = p_bet_id and x.side = p_outcome
      order by x.stake desc, x.first_seq limit v_left
    ) t
    where r.bet_id = p_bet_id and r.user_id = t.user_id;
  end if;
  update public.series_bet_results set net = payout - stake where bet_id = p_bet_id;

  update public.bet_series_participants p set balance = p.balance + r.payout
  from public.series_bet_results r
  where r.bet_id = p_bet_id and p.series_id = p_series_id and p.user_id = r.user_id;

  if not p_cancel then
    select coalesce(max(seq), 0) + 1 into v_seq from public.series_bets where series_id = p_series_id;
  end if;
  update public.series_bets set
    status = case when p_cancel then 'CANCELLED' else 'RESOLVED' end,
    winning_outcome = case when p_cancel then null else p_outcome end,
    refunded = v_refund, closed_at = coalesce(closed_at, now()), settled_at = now(), seq = v_seq
  where id = p_bet_id returning * into b;

  perform public._bs_log(p_series_id, case
    when p_cancel then 'Canceled, coins returned: ' || b.question
    when p_outcome is null then 'Everyone was on one side, so coins went back: ' || b.question
    else p_outcome || ': ' || b.question || case when v_refund then ' (everyone was on one side, so coins went back)' else '' end
  end);

  select coalesce(jsonb_agg(jsonb_build_object('userId', user_id, 'gross', payout, 'net', net, 'refunded', v_refund) order by user_id), '[]')
  into v_payouts from public.series_bet_results where bet_id = p_bet_id;

  perform public._bs_maybe_finish(p_series_id);
  return jsonb_build_object('betId', b.id, 'status', b.status, 'pool', v_total, 'refunded', v_refund, 'payouts', v_payouts);
end $$;

